#!/usr/bin/env node
// Turns the Claude Design source (design/Main.dc.html) into src/generated/prototype.js.
//
//   npm run import                      re-generate from design/Main.dc.html
//   npm run import -- ~/Downloads/Main.dc.html   copy a newer export into design/ first
//
// What it does:
//   - removes team-only blocks (wrapped in <sc-if value="{{notDemo}}">) from the copy in design/
//   - parses the template between <x-dc> and </x-dc> into a small JSON tree (AST)
//   - copies the <script type="text/x-dc"> logic as is, wrapped in createPrototype(DCLogic)
//   - points asset URLs "/_blob/<id>" at "img/<id>.jpg" (files in public/img/) and lists any missing photos
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { parseDocument } from 'htmlparser2';

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const DESIGN = path.join(ROOT, 'design/Main.dc.html');

const incoming = process.argv[2];
let html = fs.readFileSync(incoming ? path.resolve(incoming) : DESIGN, 'utf8');

// Team-only notes never ship: strip every <sc-if value="{{notDemo}}"> … </sc-if> block.
const OPEN = '<sc-if value="{{notDemo}}"';
let stripped = 0;
for (let i = html.indexOf(OPEN); i >= 0; i = html.indexOf(OPEN)) {
  let depth = 0, j = i;
  const re = /<sc-if\b|<\/sc-if>/g;
  re.lastIndex = i;
  for (let m; (m = re.exec(html));) {
    depth += m[0] === '</sc-if>' ? -1 : 1;
    if (depth === 0) { j = m.index + m[0].length; break; }
  }
  html = html.slice(0, i) + '<!-- team-only block removed -->' + html.slice(j);
  stripped++;
}
if (incoming || stripped) fs.writeFileSync(DESIGN, html);

const src = html.replace(/\/_blob\/([0-9a-f]{32})/g, 'img/$1.jpg');
const tpl = src.split('<x-dc>')[1].split('</x-dc>')[0].replace(/<helmet>[\s\S]*?<\/helmet>/, '');
const logic = src.split('data-dc-script')[1].split("'>").slice(1).join("'>").split('</script>')[0];

const doc = parseDocument(tpl, { lowerCaseAttributeNames: false, lowerCaseTags: false, recognizeSelfClosing: true });
// Node shapes: "text" | [tag, attrs, children]
function conv(nodes) {
  const out = [];
  for (const n of nodes) {
    if (n.type === 'text') {
      if (/^\s*$/.test(n.data) && /\n/.test(n.data)) continue; // formatting whitespace between tags
      out.push(n.data);
    } else if (n.type === 'tag' || n.type === 'script' || n.type === 'style') {
      out.push([n.name, n.attribs || {}, conv(n.children || [])]);
    }
  }
  return out;
}
const ast = conv(doc.children);

const missing = [...new Set(src.match(/img\/[0-9a-f]{32}\.jpg/g) || [])].filter((f) => !fs.existsSync(path.join(ROOT, 'public', f)));

const out = '/* Generated by scripts/import-design.mjs from design/Main.dc.html. Do not edit by hand. */\n' +
  '/* eslint-disable */\n' +
  'export const AST = ' + JSON.stringify(ast) + ';\n' +
  'export function createPrototype(DCLogic) {\n' + logic +
  '\nreturn { Component: Component, STROLLS: STROLLS, MAP_STROLLS: MAP_STROLLS, MAP_BY: MAP_BY, STROLL_KEY: STROLL_KEY, BOARD: typeof BOARD !== "undefined" ? BOARD : null };\n}\n';
fs.mkdirSync(path.join(ROOT, 'src/generated'), { recursive: true });
fs.writeFileSync(path.join(ROOT, 'src/generated/prototype.js'), out);
// The design file's own styles (website hover states, sticky search card, gallery, reload bar).
const helmetCss = ((html.match(/<helmet>[\s\S]*?<style>([\s\S]*?)<\/style>/) || [])[1] || '').replace('body{margin:0}', '');
fs.writeFileSync(path.join(ROOT, 'src/generated/prototype.css'), '/* Generated from design/Main.dc.html. Do not edit by hand. */\n' + helmetCss + '\n');

console.log('src/generated/prototype.js ' + (out.length / 1024).toFixed(0) + ' KB' + (stripped ? ' · removed ' + stripped + ' team-only block(s)' : ''));
if (missing.length) { console.log('Missing photos (add them to public/img/):\n  ' + missing.join('\n  ')); process.exitCode = 1; }
